"""Package reviewed local diagnostic sources into a private Kaggle GPU script.

The generated single-file kernel is an execution envelope, not a new model.
It uses only existing Kaggle datasets and never embeds credentials.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import zlib
from pathlib import Path


REPO = Path(__file__).resolve().parents[2]
TRAINER = REPO / "kaggle/armc_roi/train_armc_roi_kaggle.py"
DIAGNOSTIC = REPO / "kaggle/model_research/diagnose_armc.py"


def encode(path: Path):
    source = path.read_bytes()
    return base64.b64encode(zlib.compress(source, level=9)).decode(), hashlib.sha256(source).hexdigest()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--kernel-id")
    parser.add_argument("--amp", action="store_true", help="Use CUDA float16 autocast, matching production evaluation")
    parser.add_argument("--repeat-seed", type=int, choices=(2027, 2028),
                        help="Attach a completed Stage 2 repeat kernel and evaluate its selected checkpoint")
    args = parser.parse_args()
    if args.kernel_id is None:
        args.kernel_id = (f"manyakaistha/armc-roi-repeat-diagnostics-seed-{args.repeat_seed}"
                          if args.repeat_seed else "manyakaistha/arm-c-roi-diagnostics-2026-09-24")
    args.output.mkdir(parents=True, exist_ok=True)
    trainer, trainer_sha = encode(TRAINER)
    diagnostic, diagnostic_sha = encode(DIAGNOSTIC)
    if 'WANDB_API_KEY = ""' not in TRAINER.read_text():
        raise RuntimeError("Production trainer still contains a nonempty credential assignment")
    amp_argument = ", '--amp'" if args.amp else ""
    if args.repeat_seed:
        checkpoint_setup = """candidates = [p for p in Path('/kaggle/input').rglob('armc_roi_selected_model.pt')
              if p.is_file() and p.stat().st_size > 0]
if len(candidates) != 1:
    raise RuntimeError(f'Expected one attached repeat selected checkpoint, found {candidates}')
armc_path = str(candidates[0])
"""
        repeat_arguments = f", '--allow-global-change', '--expected-seed', '{args.repeat_seed}'"
        output_dir = f"/kaggle/working/armc_diagnostics_seed{args.repeat_seed}"
        dataset_sources = ["manyakaistha/knee-roi-data"]
        kernel_sources = [f"manyakaistha/armc-roi-repeat-seed-{args.repeat_seed}"]
    else:
        checkpoint_setup = "armc_path = '/kaggle/input/datasets/manyakaistha/knee-roi-model/armc_roi_selected_model.pt'\n"
        repeat_arguments = ""
        output_dir = "/kaggle/working/armc_diagnostics"
        dataset_sources = ["manyakaistha/knee-roi-data", "manyakaistha/knee-roi-model"]
        kernel_sources = []
    script = f'''"""Generated by package_kaggle_diagnostics.py; source digests below."""
import base64, hashlib, os, runpy, sys, zlib
from pathlib import Path
root = Path('/kaggle/working/rsna-knee-mri')
sources = [
    ('kaggle/armc_roi/train_armc_roi_kaggle.py', '{trainer_sha}', '{trainer}'),
    ('kaggle/model_research/diagnose_armc.py', '{diagnostic_sha}', '{diagnostic}'),
]
for relative, expected, packed in sources:
    data = zlib.decompress(base64.b64decode(packed))
    if hashlib.sha256(data).hexdigest() != expected:
        raise RuntimeError('Packaged source digest mismatch: ' + relative)
    path = root / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
data = Path('/kaggle/input/datasets/manyakaistha/knee-roi-data')
{checkpoint_setup}
sys.argv = [str(root / 'kaggle/model_research/diagnose_armc.py'),
    '--arm13', str(data / 'arm13_training_bundle/arm13_best.pt'),
    '--armc', armc_path,
    '--global-cache', str(data / 'armc_kaggle_upload/roi_work/cache64'),
    '--roi-cache', str(data / 'armc_kaggle_upload/roi_work/cache_merged'),
    '--gold', str(data / 'gold_test.csv'),
    '--output', '{output_dir}',
    '--device', 'cuda', '--threads', '4'{amp_argument}{repeat_arguments}]
os.environ['WANDB_MODE'] = 'disabled'
runpy.run_path(sys.argv[0], run_name='__main__')
'''
    (args.output / "run.py").write_text(script)
    metadata = {
        "id": args.kernel_id, "title": args.kernel_id.split("/", 1)[1],
        "code_file": "run.py", "language": "python", "kernel_type": "script",
        "is_private": True, "enable_gpu": True, "enable_tpu": False,
        "enable_internet": False,
        "dataset_sources": dataset_sources,
        "competition_sources": [], "kernel_sources": kernel_sources, "model_sources": [],
    }
    (args.output / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")
    print(json.dumps({"package": str(args.output), "trainer_sha256": trainer_sha,
                      "diagnostic_sha256": diagnostic_sha,
                      "kernel_script_sha256": hashlib.sha256(script.encode()).hexdigest()}, indent=2))


if __name__ == "__main__":
    main()
